# -*- coding: utf-8 -*-
"""Лаба 9: оборотный регистр накопления Продажи, проведение ОказаниеУслуги по трём регистрам, отчёт РеестрДокументовОказаниеУслуги."""
import sys, os
sys.path.insert(0, os.path.dirname(__file__))
from labgen import *
from regs import accreg_xml
import forms

NOM = t_ref('CatalogRef.Номенклатура'); KLI = t_ref('CatalogRef.Клиенты'); SOT = t_ref('CatalogRef.Сотрудники')

# ===== Оборотный регистр Продажи =====
write('AccumulationRegisters/Продажи.xml', accreg_xml('Продажи', 'Turnovers',
      [('Номенклатура', NOM), ('Клиент', KLI), ('Мастер', SOT)],
      [('Количество', t_num(15, 3, False)), ('Выручка', t_num(15, 2, False)), ('Стоимость', t_num(15, 2, False))],
      ext_pres='Движения документа по регистру Продажи'))
cfg_add('AccumulationRegister', 'Продажи')
for sub in ('Бухгалтерия', 'УчетМатериалов', 'ОказаниеУслуг'):
    sub_content_add(sub, 'AccumulationRegister.Продажи')
    ci_visible(sub, 'AccumulationRegister.Продажи.StandardCommand.OpenList')
    ci_placement(sub, 'AccumulationRegister.Продажи.StandardCommand.OpenList', 'NavigationPanelSeeAlso')

# ===== ОказаниеУслуги: движения по Продажам =====
p = 'Documents/ОказаниеУслуги.xml'
t = read(p)
item = '<xr:Item xsi:type="xr:MDObjectRef">AccumulationRegister.Продажи</xr:Item>'
if item not in t:
    t = t.replace('\t\t\t</RegisterRecords>', f'\t\t\t\t{item}\n\t\t\t</RegisterRecords>', 1)
    write(p, t)

write('Documents/ОказаниеУслуги/Ext/ObjectModule.bsl',
'''Процедура ОбработкаПроведения(Отказ, Режим)

	Движения.ОстаткиМатериалов.Записывать = Истина;
	Движения.СтоимостьМатериалов.Записывать = Истина;
	Движения.Продажи.Записывать = Истина;

	Для Каждого ТекСтрокаПереченьНоменклатуры Из ПереченьНоменклатуры Цикл
		Если ТекСтрокаПереченьНоменклатуры.Номенклатура.ВидНоменклатуры = Перечисления.ВидыНоменклатуры.Материал Тогда

			// Регистр ОстаткиМатериалов Расход
			Движение = Движения.ОстаткиМатериалов.Добавить();
			Движение.ВидДвижения = ВидДвиженияНакопления.Расход;
			Движение.Период = Дата;
			Движение.Материал = ТекСтрокаПереченьНоменклатуры.Номенклатура;
			Движение.Склад = Склад;
			Движение.Количество = ТекСтрокаПереченьНоменклатуры.Количество;

			// Регистр СтоимостьМатериалов Расход
			Движение = Движения.СтоимостьМатериалов.Добавить();
			Движение.ВидДвижения = ВидДвиженияНакопления.Расход;
			Движение.Период = Дата;
			Движение.Материал = ТекСтрокаПереченьНоменклатуры.Номенклатура;
			Движение.Стоимость = ТекСтрокаПереченьНоменклатуры.Количество * ТекСтрокаПереченьНоменклатуры.Стоимость;

		КонецЕсли;

		// Регистр Продажи (услуги и материалы)
		Движение = Движения.Продажи.Добавить();
		Движение.Период = Дата;
		Движение.Номенклатура = ТекСтрокаПереченьНоменклатуры.Номенклатура;
		Движение.Клиент = Клиент;
		Движение.Мастер = Мастер;
		Движение.Количество = ТекСтрокаПереченьНоменклатуры.Количество;
		Движение.Выручка = ТекСтрокаПереченьНоменклатуры.Сумма;
		Движение.Стоимость = ТекСтрокаПереченьНоменклатуры.Стоимость * ТекСтрокаПереченьНоменклатуры.Количество;

	КонецЦикла;

КонецПроцедуры
''')

CMD = ('AccumulationRegister.Продажи.StandardCommand.OpenByRecorder', 'FormNavigationPanelGoTo')
if CMD not in forms.S['ОказаниеУслуги']['nav']:
    forms.S['ОказаниеУслуги']['nav'].append(CMD)

# ===== Отчёт РеестрДокументовОказаниеУслуги =====
QUERY = '''ВЫБРАТЬ
	ОказаниеУслуги.Склад КАК Склад,
	ОказаниеУслуги.Мастер КАК Мастер,
	ОказаниеУслуги.Клиент КАК Клиент,
	ОказаниеУслуги.Ссылка КАК Документ
ИЗ
	Документ.ОказаниеУслуги КАК ОказаниеУслуги
ГДЕ
	ОказаниеУслуги.Дата МЕЖДУ &ДатаС И &ДатаПо

УПОРЯДОЧИТЬ ПО
	Документ'''
FIELDS = ['Склад', 'Мастер', 'Клиент', 'Документ']
fields_xml = ''.join(dcs_field(f) for f in FIELDS)
params_xml = (dcs_param('ДатаС', 'Дата с', DATE_TYPE, DATE_ZERO, restrict=False) +
              dcs_param('ДатаПо', 'Дата по', DATE_TYPE, DATE_ZERO, restrict=False))
sel = sel_items(['SystemFields.SerialNumber'] + FIELDS, 4)
dparams = (data_param('ДатаС', std_date('BeginningOfThisMonth'), 'Q/РеестрОУ/С') +
           data_param('ДатаПо', std_date('BeginningOfNextMonth'), 'Q/РеестрОУ/По'))
sch = dcs_schema(fields_xml, QUERY, [('Документ', 'Количество(Документ)')], params_xml, sel, dparams, group_item(None, '', 3))
report_files('РеестрДокументовОказаниеУслуги', sch, ['ОказаниеУслуг'], synonym='Реестр документов оказание услуги')
print('batch7 ok')

def write_forms():
    for doc, c in S.items():
        cols = [tuple(x) for x in c['columns']]
        write(f'Documents/{doc}/Forms/ФормаДокумента/Ext/Form.xml',
              document_form_xml(doc, c['header'], c['table'], cols, nav_items=c['nav'], cmdbar_items=c['cmdbar'], footer=c['footer']))
        write(f'Documents/{doc}/Forms/ФормаДокумента/Ext/Form/Module.bsl', '\n'.join(h.rstrip('\n') + '\n' for h in c['handlers']))
    write('Documents/ОказаниеУслуги/Forms/ФормаДокумента.xml', form_meta_xml('F/ОказаниеУслуги/ФормаДокумента'))

def build(doc, table, hdr_params, hdr_labels, col_params, col_titles, tchild_query_fields, header_query):
    # --- макет ---
    widths = [30, 180, 60, 60, 80]
    rows = []
    rows.append([(0, 'text', human(doc) + ' №', True), (1, 'param', 'Заголовок', True)])
    cells = []
    for i, (p, l) in enumerate(zip(hdr_params, hdr_labels)):
        rows_h = [(0, 'text', l + ':', False), (1, 'param', p, False)]
        rows.append(rows_h)
    n_hdr = len(hdr_params)
    rows.append([(i, 'text', t, True) for i, t in enumerate(col_titles)])
    rows.append([(i, 'param', p, False) for i, p in enumerate(col_params)])
    rows.append([(3, 'text', 'ВСЕГО:', True), (4, 'param', 'ВсегоПоДокументу', True)])
    named = [('Заголовок', 0, 0), ('Шапка', 1, n_hdr), ('ШапкаТаблицы', n_hdr + 1, n_hdr + 1),
             ('Строка', n_hdr + 2, n_hdr + 2), ('Всего', n_hdr + 3, n_hdr + 3)]
    sheet = sheet_xml(widths, rows, named)
    # --- менеджер ---
    hdr_fields = ',\n\t'.join(f'Документ.{f} КАК {a}' for a, f in header_query)
    row_fields = ',\n\t'.join(f'Документ{table}.{f} КАК {a}' for a, f in tchild_query_fields)
    hdr_assign = '\n'.join(f'\tОбластьШапка.Параметры.{a} = Выборка.{a};' for a, f in header_query)
    row_assign = '\n'.join(f'\t\tОбластьСтрока.Параметры.{a} = ВыборкаСтроки.{a};' for a, f in tchild_query_fields)
    mgr = f'''Процедура Печать(ТабДок, МассивОбъектов, ОбъектыПечати, ИмяМакета) Экспорт
	Макет = Документы.{doc}.ПолучитьМакет("Печать");
	Запрос = Новый Запрос;
	Запрос.Текст =
		"ВЫБРАТЬ
		|	Документ.Ссылка КАК Ссылка,
		|	Документ.Номер КАК Номер,
		|	Документ.Дата КАК Дата,
		|	{hdr_fields.replace(chr(10), chr(10) + chr(9) + '|')}
		|ИЗ
		|	Документ.{doc} КАК Документ
		|ГДЕ
		|	Документ.Ссылка В(&МассивОбъектов)";
	Запрос.УстановитьПараметр("МассивОбъектов", МассивОбъектов);
	Шапка = Запрос.Выполнить().Выбрать();
	Пока Шапка.Следующий() Цикл
		ОбластьЗаголовок = Макет.ПолучитьОбласть("Заголовок");
		ОбластьЗаголовок.Параметры.Заголовок = Шапка.Номер + " от " + Формат(Шапка.Дата, "ДЛФ=D");
		ТабДок.Вывести(ОбластьЗаголовок);
		ОбластьШапка = Макет.ПолучитьОбласть("Шапка");
		ОбластьШапка.Параметры.Заполнить(Шапка);
		ТабДок.Вывести(ОбластьШапка);
		ТабДок.Вывести(Макет.ПолучитьОбласть("ШапкаТаблицы"));
		ЗапросСтроки = Новый Запрос;
		ЗапросСтроки.Текст =
			"ВЫБРАТЬ
			|	Документ{table}.НомерСтроки КАК НомерСтроки,
			|	{row_fields.replace(chr(10), chr(10) + chr(9) + '|')}
			|ИЗ
			|	Документ.{doc}.{table} КАК Документ{table}
			|ГДЕ
			|	Документ{table}.Ссылка = &Ссылка
			|
			|УПОРЯДОЧИТЬ ПО
			|	Документ{table}.НомерСтроки";
		ЗапросСтроки.УстановитьПараметр("Ссылка", Шапка.Ссылка);
		ВыборкаСтроки = ЗапросСтроки.Выполнить().Выбрать();
		ОбластьСтрока = Макет.ПолучитьОбласть("Строка");
		ОбластьИтог = Макет.ПолучитьОбласть("Всего");
		СуммаИтог = 0;
		Пока ВыборкаСтроки.Следующий() Цикл
			ОбластьСтрока.Параметры.Заполнить(ВыборкаСтроки);
			ТабДок.Вывести(ОбластьСтрока);
			СуммаИтог = СуммаИтог + ВыборкаСтроки.Сумма;
		КонецЦикла;
		ОбластьИтог.Параметры.ВсегоПоДокументу = СуммаИтог;
		ТабДок.Вывести(ОбластьИтог);
	КонецЦикла;
КонецПроцедуры
'''
    cmd = f'''&НаКлиенте
Процедура ОбработкаКоманды(ПараметрКоманды, ПараметрыВыполненияКоманды)
	ТабДок = Новый ТабличныйДокумент;
	ПечатьНаСервере(ТабДок, ПараметрКоманды);
	ТабДок.Показать();
КонецПроцедуры

&НаСервере
Процедура ПечатьНаСервере(ТабДок, ПараметрКоманды)
	МассивОбъектов = Новый Массив;
	МассивОбъектов.Добавить(ПараметрКоманды);
	Документы.{doc}.Печать(ТабДок, МассивОбъектов, Неопределено, "Печать");
КонецПроцедуры
'''
    add_print_form(doc, sheet, mgr, cmd)
    s = forms.S[doc]
    s['cmdbar'] = [(f'Document.{doc}.Command.Печать', 'FormCommandBarImportant')]
    s['footer'] = True
    s['columns'][2].append(('Всего', None))
    s['columns'][3].append((None, f'Объект.{table}.TotalСумма'))

build('ОказаниеУслуги', 'ПереченьНоменклатуры',
      ['Склад', 'Клиент', 'Мастер'], ['Склад', 'Клиент', 'Мастер'],
      ['НомерСтроки', 'Номенклатура', 'Количество', 'Цена', 'Сумма'], ['N', 'Номенклатура', 'Количество', 'Цена', 'Сумма'],
      [('Номенклатура', 'Номенклатура'), ('Количество', 'Количество'), ('Цена', 'Цена'), ('Сумма', 'Сумма')],
      [('Склад', 'Склад'), ('Клиент', 'Клиент'), ('Мастер', 'Мастер')])
build('ПриходнаяНакладная', 'Материалы',
      ['Склад'], ['Склад'],
      ['НомерСтроки', 'Материал', 'Количество', 'Цена', 'Сумма'], ['N', 'Материал', 'Количество', 'Цена', 'Сумма'],
      [('Материал', 'Материал'), ('Количество', 'Количество'), ('Цена', 'Цена'), ('Сумма', 'Сумма')],
      [('Склад', 'Склад')])

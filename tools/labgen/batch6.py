NOM = t_ref('CatalogRef.Номенклатура')

# ===== Регистр накопления СтоимостьМатериалов =====
write('AccumulationRegisters/СтоимостьМатериалов.xml', accreg_xml('СтоимостьМатериалов', 'Balance',
      [('Материал', NOM)], [('Стоимость', t_num(15, 2, False))], ext_pres='Движения по регистру Стоимость материалов'))
cfg_add('AccumulationRegister', 'СтоимостьМатериалов')
for sub in ('УчетМатериалов', 'ОказаниеУслуг', 'Бухгалтерия'):
    sub_content_add(sub, 'AccumulationRegister.СтоимостьМатериалов')
